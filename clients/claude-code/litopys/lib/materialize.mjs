// Agents and skills of the layers as files Claude Code can load. Claude Code takes agents and
// skills only from files, so in both modes (files | memory concerns CLAUDE.md only) the plugin writes them
// into the bound folder's .claude/agents and .claude/skills, keeps them out of git (.git/info/exclude, local
// only) and touches only the files it generated (the marker line below). Restorable, never primary.
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const MARK = "<!-- generated by Litopys from the layer rules; edits go to Litopys (/litopys:layers) -->";
const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

// a plain YAML scalar ends at " #" (a comment) and breaks on ": " or a leading indicator: such a value is quoted
const UNSAFE_PLAIN = /\s#|:\s|^[-?:,[\]{}#&*!|>'"%@`]/;
const quoted = (v) => `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

// withFrontmatter: a rule value without frontmatter gets the minimal one Claude Code needs; a value with its own
// frontmatter keeps it, with name and description quoted when a plain scalar would cut them. Returns the
// content and the name Claude Code registers the agent under (the frontmatter name).
function withFrontmatter(key, value) {
  const text = (value || "").replace(/\r\n/g, "\n").trim();
  const fm = text.match(/^---\n([\s\S]*?)\n---(\n|$)/);
  if (fm) {
    let name = key;
    const lines = fm[1].split("\n").map((l) => {
      const m = l.match(/^(name|description):[ \t]*(.*)$/);
      if (!m) return l;
      let v = m[2].trim();
      if (!/^["']/.test(v) && UNSAFE_PLAIN.test(v)) v = quoted(v);
      if (m[1] === "name") name = v.replace(/^["']|["']$/g, "") || key;
      return `${m[1]}: ${v}`;
    });
    return { content: `---\n${lines.join("\n")}\n---${fm[2]}${text.slice(fm[0].length)}`, name };
  }
  const first = text.split("\n").find((l) => l.trim()) || key;
  const description = first.replace(/^#+\s*/, "").replace(/"/g, "'").slice(0, 200);
  return { content: `---\nname: ${key}\ndescription: "${description}"\n---\n\n${text}`, name: key };
}

// insert the mark after the frontmatter (Claude Code reads the frontmatter from the first line)
function marked(content) {
  const m = content.match(/^---\n[\s\S]*?\n---\n/);
  return m ? `${m[0]}${MARK}\n${content.slice(m[0].length)}\n` : `${MARK}\n${content}\n`;
}

const isOurs = (file) => existsSync(file) && readFileSync(file, "utf8").includes(MARK);

function excludeFromGit(folder, patterns) {
  const info = join(folder, ".git", "info");
  if (!existsSync(join(folder, ".git"))) return false;
  mkdirSync(info, { recursive: true });
  const file = join(info, "exclude");
  const have = existsSync(file) ? readFileSync(file, "utf8").split(/\r?\n/) : [];
  const add = patterns.filter((p) => !have.includes(p));
  if (add.length) appendFileSync(file, (have.length && have[have.length - 1] !== "" ? "\n" : "") + add.join("\n") + "\n");
  return true;
}

// materialize writes the agent and skill rules of a resolved stack into folder/.claude and removes generated
// files whose rule is gone. Returns what changed.
export function materialize(folder, layers) {
  const agentsDir = join(folder, ".claude", "agents");
  const skillsDir = join(folder, ".claude", "skills");
  const want = { agent: new Map(), skill: new Map() };
  const skipped = [];
  for (const r of layers?.stack || []) {
    if (r.kind !== "agent" && r.kind !== "skill") continue;
    if (!SAFE_KEY.test(r.key)) {
      skipped.push(`${r.kind}/${r.key}`);
      continue;
    }
    const { content, name } = withFrontmatter(r.key, r.value);
    // an agent registers under its frontmatter name, a skill under its directory
    want[r.kind].set(r.key, { content: marked(content), name: r.kind === "agent" ? name : `litopys-${r.key}` });
  }
  const written = [];
  const removed = [];
  // {kind, key, name, fresh} of the rules with a generated file; fresh = written by this call — Claude Code
  // loads agents and skills when a session starts, so a fresh file is not loaded yet
  const present = [];
  const put = (kind, key, file, { content, name }) => {
    if (existsSync(file) && !isOurs(file)) {
      skipped.push(`${file} (a file not generated by Litopys — left as is)`);
      return;
    }
    const same = existsSync(file) && readFileSync(file, "utf8") === content;
    present.push({ kind, key, name, fresh: !same });
    if (same) return;
    mkdirSync(join(file, ".."), { recursive: true });
    writeFileSync(file, content);
    written.push(file);
  };
  for (const [key, w] of want.agent) put("agent", key, join(agentsDir, `litopys-${key}.md`), w);
  for (const [key, w] of want.skill) put("skill", key, join(skillsDir, `litopys-${key}`, "SKILL.md"), w);
  // stale generated files: their rule left the stack
  if (existsSync(agentsDir)) {
    for (const f of readdirSync(agentsDir)) {
      const m = f.match(/^litopys-(.+)\.md$/);
      const file = join(agentsDir, f);
      if (m && !want.agent.has(m[1]) && isOurs(file)) {
        rmSync(file);
        removed.push(file);
      }
    }
  }
  if (existsSync(skillsDir)) {
    for (const d of readdirSync(skillsDir)) {
      const m = d.match(/^litopys-(.+)$/);
      const file = join(skillsDir, d, "SKILL.md");
      if (m && !want.skill.has(m[1]) && isOurs(file)) {
        rmSync(join(skillsDir, d), { recursive: true, force: true });
        removed.push(file);
      }
    }
  }
  const gitExcluded = written.length || want.agent.size || want.skill.size
    ? excludeFromGit(folder, [".claude/agents/litopys-*.md", ".claude/skills/litopys-*/"])
    : false;
  return { written, removed, skipped, present, gitExcluded, agents: want.agent.size, skills: want.skill.size };
}
